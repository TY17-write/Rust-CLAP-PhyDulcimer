//! ハンマーダルシマーの物理モデル DSP コア。
//!
//! このクレートはオーディオスレッドから呼ばれるコードだけを持つ。したがって以下を守る:
//!
//! - ヒープ確保をしない (バッファは呼び出し側が事前確保して渡す)
//! - ロックを取らない
//! - ファイル I/O をしない
//! - オーディオ経路で panic しうる操作 (添字外アクセス、`unwrap`) をしない
//!
//! 段階的に構築中。現在は **Phase 0 — 土台**。モデル本体はまだ無く、
//! `tools/render` → WAV → `tools/analyze` の経路を検証するための
//! [`smoke`] だけが入っている。
//!
//! この音源がピアノと構造的に違う点 (ダンパーが無い / ブリッジが弦を 2 つに分ける /
//! 打弦点が可変 / X-Y の部屋を内蔵する) は `docs/plan.html` を参照。

#![forbid(unsafe_code)]

pub mod smoke;

/// オーディオ処理で使う標本の型。
///
/// モーダル共振器は本数が支配的なので、SIMD 幅を稼げる `f32` を既定とする。
/// 係数計算 (周波数・減衰の設計) は `f64` で行ってから `f32` に落とす。
pub type Sample = f32;

/// 開発・テスト時の既定サンプリング周波数。
pub const DEFAULT_SAMPLE_RATE: f64 = 48_000.0;

/// A4 の基準周波数。
pub const A4_HZ: f64 = 440.0;

/// A4 の MIDI ノート番号。
pub const A4_MIDI: u8 = 69;
